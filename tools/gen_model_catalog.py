#!/usr/bin/env python3
"""Generate desktop and Android catalog definitions from the pinned model list."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "assets/model-catalog.json"
DESKTOP = ROOT / "server/model_catalog.inc"
ANDROID = ROOT / "apps/android/app/src/main/java/dev/dubhe/mobile/ModelCatalog.kt"


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def valid_file(file):
    return (
        re.fullmatch(r"[\w.-]+\.gguf", file["file"])
        and re.fullmatch(r"[a-f0-9]{64}", file["sha256"])
        and type(file["bytes"]) is int
        and 0 < file["bytes"] < 2**53
    )


def validate(rows):
    files = [row["file"] for row in rows] + [row["projector"]["file"] for row in rows if "projector" in row]
    orders = [row["android"]["order"] for row in rows if "android" in row]
    for name, values in (("id", [row["id"] for row in rows]), ("file", files), ("Android order", orders)):
        if len(set(values)) != len(values):
            raise ValueError(f"Duplicate model {name}")
    for row in rows:
        if not (
            re.fullmatch(r"[a-z0-9-]+", row["id"])
            and re.fullmatch(r"[\w.-]+/[\w.-]+", row["repository"])
            and re.fullmatch(r"[a-f0-9]{40}", row["revision"])
            and valid_file(row)
        ):
            raise ValueError(f"Invalid pinned file in {row['id']}")
        if row.get("translation") not in (None, "hy", "index"):
            raise ValueError(f"Unknown translation template in {row['id']}")
        projector = row.get("projector")
        if "modality" in row or "projector" in row:
            if not (projector and row.get("modality") in ("image", "audio")
                    and not row.get("scan") and not row.get("translation")
                    and valid_file(projector) and projector["file"].startswith("mmproj-")
                    and row["bytes"] + projector["bytes"] < 2**53):
                raise ValueError(f"Invalid multimodal files in {row['id']}")


def url(row, file):
    return f"https://huggingface.co/{row['repository']}/resolve/{row['revision']}/{file['file']}"


def desktop(rows):
    content = ["// Generated by tools/gen_model_catalog.py. Edit assets/model-catalog.json."]
    for row in rows:
        identity = ", ".join(quote(row[field]) for field in ("id", "name", "params", "quant"))
        prefix = f"https://huggingface.co/{row['repository']}/resolve/"
        suffix = f"{row['revision']}/{row['file']}"
        translation = quote(row["translation"]) if "translation" in row else "nullptr"
        scan = str(row.get("scan", False)).lower()
        recommended = str(row.get("recommended", False)).lower()
        fields = [
            f"    {{{identity}, {row['bytes']}LL,",
            f"     {quote(row['file'])},",
            f"     {quote(prefix)}",
            f"     {quote(suffix)},",
            f"     {quote(row['sha256'])}, {translation}, {scan}, {recommended}",
        ]
        if "projector" in row:
            projector = row["projector"]
            fields[-1] += ","
            fields.extend([
                f"     {{{projector['bytes']}LL, {quote(projector['file'])},",
                f"      {quote(url(row, projector))},",
                f"      {quote(projector['sha256'])}}}, {quote(row['modality'])}",
            ])
        fields[-1] += "},"
        content.extend(fields)
    return "\n".join(content) + "\n"


def android(rows):
    content = ["""// Generated by tools/gen_model_catalog.py. Edit assets/model-catalog.json.
package dev.dubhe.mobile

internal enum class CatalogModality { IMAGE, AUDIO }

internal data class CatalogFile(
    val file: String,
    val bytes: Long,
    val repository: String,
    val revision: String,
    val sha256: String,
) {
    val url: String get() = "https://huggingface.co/$repository/resolve/$revision/$file"
}

internal data class CatalogModel(
    val name: String,
    val description: String,
    val file: String,
    val bytes: Long,
    val repository: String,
    val revision: String,
    val sha256: String,
    val translation: Boolean = false,
    val recommended: Boolean = false,
    val projector: CatalogFile? = null,
    val modality: CatalogModality? = null,
) {
    val url: String get() = "https://huggingface.co/$repository/resolve/$revision/$file"
    val totalBytes: Long get() = bytes + (projector?.bytes ?: 0L)
}

internal val mobileCatalog = listOf("""]
    for row in sorted((row for row in rows if "android" in row), key=lambda row: row["android"]["order"]):
        app = row["android"]
        intro = ", ".join(quote(value) for value in (app["name"], app["description"], row["file"]))
        bits = ", ".join(quote(row[field]) for field in ("repository", "revision"))
        flags = ", translation = true" if "translation" in row else ""
        if row.get("recommended"):
            flags += ", recommended = true"
        fields = [
            "    CatalogModel(",
            f"        {intro},",
            f"        {row['bytes']}L, {bits},",
            f"        {quote(row['sha256'])}{flags},",
        ]
        if "projector" in row:
            projector = row["projector"]
            fields.extend([
                "        projector = CatalogFile(",
                f"            {quote(projector['file'])}, {projector['bytes']}L, {bits},",
                f"            {quote(projector['sha256'])},",
                "        ),",
                f"        modality = CatalogModality.{row['modality'].upper()},",
            ])
        content.extend(fields + ["    ),"])
    return "\n".join(content + [")", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = json.loads(CATALOG.read_text(encoding="utf-8"))
    validate(rows)
    for path, content in ((DESKTOP, desktop(rows)), (ANDROID, android(rows))):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                parser.error(f"{path.relative_to(ROOT)} is stale. Run tools/gen_model_catalog.py.")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
