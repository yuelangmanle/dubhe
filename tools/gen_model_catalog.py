#!/usr/bin/env python3
"""Generate desktop and Android catalog definitions from the pinned model list."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "assets/model-catalog.json"
DESKTOP = ROOT / "server/model_catalog.inc"
ANDROID = ROOT / "apps/android/app/src/main/java/dev/dubhe/mobile/ModelCatalog.kt"


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def validate(rows):
    for field in ("id", "file"):
        if len({row[field] for row in rows}) != len(rows):
            raise ValueError(f"Duplicate model {field}")
    for row in rows:
        if not (
            re.fullmatch(r"[a-z0-9-]+", row["id"])
            and re.fullmatch(r"[\w.-]+/[\w.-]+", row["repository"])
            and re.fullmatch(r"[\w.-]+\.gguf", row["file"])
            and re.fullmatch(r"[a-f0-9]{40}", row["revision"])
            and re.fullmatch(r"[a-f0-9]{64}", row["sha256"])
            and isinstance(row["bytes"], int)
            and 0 < row["bytes"] < 2**53
        ):
            raise ValueError(f"Invalid pinned file in {row['id']}")
        if row.get("translation") not in (None, "hy", "index"):
            raise ValueError(f"Unknown translation template in {row['id']}")


def desktop(rows):
    content = ["// Generated by tools/gen_model_catalog.py. Edit assets/model-catalog.json."]
    for row in rows:
        identity = ", ".join(quote(row[field]) for field in ("id", "name", "params", "quant"))
        prefix = f"https://huggingface.co/{row['repository']}/resolve/"
        suffix = f"{row['revision']}/{row['file']}"
        translation = quote(row["translation"]) if "translation" in row else "nullptr"
        scan = str(row.get("scan", False)).lower()
        recommended = str(row.get("recommended", False)).lower()
        content.extend([
            f"    {{{identity}, {row['bytes']}LL,",
            f"     {quote(row['file'])},",
            f"     {quote(prefix)}",
            f"     {quote(suffix)},",
            f"     {quote(row['sha256'])}, {translation}, {scan}, {recommended}}},",
        ])
    return "\n".join(content) + "\n"


def android(rows):
    content = ["""// Generated by tools/gen_model_catalog.py. Edit assets/model-catalog.json.
package dev.dubhe.mobile

internal data class CatalogModel(
    val name: String,
    val description: String,
    val file: String,
    val bytes: Long,
    val repository: String,
    val revision: String,
    val sha256: String,
    val translation: Boolean = false,
    val recommended: Boolean = false,
) {
    val url: String get() = "https://huggingface.co/$repository/resolve/$revision/$file"
}

internal val mobileCatalog = listOf("""]
    for row in sorted((row for row in rows if "android" in row), key=lambda row: row["android"]["order"]):
        app = row["android"]
        intro = ", ".join(quote(value) for value in (app["name"], app["description"], row["file"]))
        bits = ", ".join(quote(row[field]) for field in ("repository", "revision"))
        flags = ", translation = true" if "translation" in row else ""
        if row.get("recommended"):
            flags += ", recommended = true"
        content.extend([
            "    CatalogModel(",
            f"        {intro},",
            f"        {row['bytes']}L, {bits},",
            f"        {quote(row['sha256'])}{flags},",
            "    ),",
        ])
    return "\n".join(content + [")", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rows = json.loads(CATALOG.read_text(encoding="utf-8"))
    validate(rows)
    for path, content in ((DESKTOP, desktop(rows)), (ANDROID, android(rows))):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                parser.error(f"{path.relative_to(ROOT)} is stale. Run tools/gen_model_catalog.py.")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
